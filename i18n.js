const LANG_LABELS = { en:'EN', vi:'VI', zh:'ZH', ko:'KO', ja:'JA', es:'ES', fr:'FR' };

function applyLang(lang){
  if (!I18N[lang]) lang = 'en';
  document.documentElement.lang = lang;
  document.body.dataset.lang = lang;
  localStorage.setItem('hasaki-lang', lang);
  const dict = I18N[lang];
  const en = I18N.en;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const k = el.getAttribute('data-i18n');
    const val = dict[k] !== undefined ? dict[k] : en[k];
    if (val !== undefined) {
      const attr = el.getAttribute('data-i18n-attr');
      if (attr) el.setAttribute(attr, val);
      else el.textContent = val;
    }
  });
  document.querySelectorAll('.lang-current').forEach(el => el.textContent = LANG_LABELS[lang]);
  document.querySelectorAll('.lang-opt').forEach(b => {
    b.classList.toggle('bg-cream', b.dataset.lang === lang);
  });
}

document.addEventListener('DOMContentLoaded', () => {
  const btn = document.getElementById('langBtn');
  const menu = document.getElementById('langMenu');
  if (btn && menu) {
    btn.addEventListener('click', e => {
      e.stopPropagation();
      menu.classList.toggle('hidden');
      btn.setAttribute('aria-expanded', !menu.classList.contains('hidden'));
    });
    document.addEventListener('click', e => {
      if (!menu.contains(e.target) && e.target !== btn) {
        menu.classList.add('hidden');
        btn.setAttribute('aria-expanded', 'false');
      }
    });
    menu.querySelectorAll('.lang-opt').forEach(b => {
      b.addEventListener('click', () => {
        applyLang(b.dataset.lang);
        menu.classList.add('hidden');
        btn.setAttribute('aria-expanded', 'false');
      });
    });
  }
  const saved = localStorage.getItem('hasaki-lang') ||
                (navigator.language || 'en').slice(0, 2).toLowerCase();
  applyLang(I18N[saved] ? saved : 'en');
});
