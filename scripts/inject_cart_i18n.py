LANGS = ['en','vi','zh','ko','ja','es','fr']

for i, lang in enumerate(LANGS):
    start_re = re.compile(rf"^  {lang}: \{{$", re.MULTILINE)
    m = start_re.search(src)
    if not m:
        print(f"  ! no start for {lang}"); continue
    next_lang_pos = None
    for j in range(i+1, len(LANGS)):
        nm = re.compile(rf"^  {LANGS[j]}: \{{$", re.MULTILINE).search(src, m.end())
        if nm:
            next_lang_pos = nm.start(); break
    end_marker = next_lang_pos if next_lang_pos else src.find('};', m.end())
    closing_re = re.compile(r'^[ ]*\},$', re.MULTILINE)
    candidates = list(closing_re.finditer(src, m.end(), end_marker))
    if not candidates:
        print(f"  ! no closing for {lang}"); continue
    close = candidates[-1]
    kv = addons[lang]
    js_lines = []
    for k, v in kv.items():
        if "'" in v and '"' not in v:
            js_lines.append(f'    "{k}": "{v}",')
        else:
            v_esc = v.replace("\\", "\\\\").replace("'", "\\'")
            js_lines.append(f"    '{k}': '{v_esc}',")
    insertion = "\n".join(js_lines) + "\n  "
    src = src[:close.start()] + insertion + src[close.start():]
    print(f"  ok injected {len(kv)} keys into {lang}")

open(p, "w").write(src)
